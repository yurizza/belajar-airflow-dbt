select
    pt.payment_id,
    pt.payment_reference,
    pt.invoice_number,
    pt.customer_key,
    c.customer_id,
    c.first_name,
    c.last_name,
    pt.transaction_date,
    pt.transaction_time,
    pt.payment_method_id,
    pt.currency_code,
    pt.payment_gateway,
    pt.payment_status,
    pt.gross_amount_usd,
    pt.discount_usd,
    pt.tax_usd,
    pt.net_amount_usd,
    pt.refund_amount_usd,
    pt.gateway_fee_usd,
    pt.installment_months,
    pt.source_type,
    pt.source_reference
from "warehouse"."main"."stg_payment_transaction" pt
left join "warehouse"."main"."stg_customer" c on pt.customer_key = c.customer_key